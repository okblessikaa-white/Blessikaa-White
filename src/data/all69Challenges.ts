export function createFullChallengeFromCatalog(catalog: CatalogChallenge): Challenge {
  const days: Challenge['days'] = Array.from({ length: 21 }, (_, i) => {
    const dayNum = i + 1;
    const taskTitle =
      dayNum === 1
        ? catalog.sampleDay1
        : `Day ${dayNum} Focus: Practice intentional ${catalog.title.toLowerCase()} action.`;
    return {
      day: dayNum,
      title: `Day ${dayNum}: ${catalog.title}`,
      description: `${catalog.description} (Day ${dayNum} of 21)`,
      tasks: [
        taskTitle,
        'Write 2 sentences of personal reflection in your journal',
        dayNum % 3 === 0
          ? 'Share your progress reflection with a friend or in community feed'
          : 'Dedicate 5 mindful minutes to acknowledge your growth',
      ],
      tip: `Focus on progress, not perfection. Step ${dayNum} is building lasting neural pathways.`,
      estimatedMinutes: 15,
      suggestedTimerMinutes: 15,
      psychologyTip: `Day ${dayNum} neuroplastic reinforcement: Repetition cements subconscious behavior into natural instinct.`,
    };
  });

  return {
    id: catalog.id,
    title: `21-Day ${catalog.title}`,
    description: catalog.description,
    category: catalog.category,
    intensity: 'intermediate',
    iconName: catalog.icon,
    tags: [catalog.categoryLabel, catalog.title, '21 Days'],
    milestone7: `Day 7 Breakthrough: Foundation of ${catalog.title} established`,
    milestone14: `Day 14 Threshold: Subconscious automaticity taking root`,
    milestone21: `Day 21 Master: Completed 21-day transformation in ${catalog.title}`,
    createdAt: new Date().toISOString(),
    days,
  };
}

