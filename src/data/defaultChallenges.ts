// Helper to generate full 21 rich daily steps for challenges
function generate21Days(
  title: string,
  category: ChallengeCategory,
  themeFocus: string,
  dailyRoutines: { title: string; task: string; tip: string; minutes: number }[]
): DayPlan[] {
  return Array.from({ length: 21 }, (_, i) => {
    const dayNum = i + 1;
    const template = dailyRoutines[i % dailyRoutines.length];
    return {
      day: dayNum,
      title: `Day ${dayNum}: ${template.title}`,
      description: `${themeFocus} — Step into Day ${dayNum} to reinforce your subconscious neural pathways.`,
      tasks: [
        template.task,
        `Document your emotional reflection in the Blessikaa journal`,
        dayNum % 3 === 0 ? `Express gratitude for your consistency progress` : `Complete 5-minute conscious breathwork before bed`,
      ],
      tip: template.tip,
      estimatedMinutes: template.minutes,
      suggestedTimerMinutes: template.minutes,
      psychologyTip: `Day ${dayNum} reinforces habit automaticity. Repetition decreases cognitive load and ingrains neuroplastic mastery.`,
    };
  });
}

