export interface FormFieldDef {
  id: string;
  label: string;
  description?: string;
  category:
    | 'basic'
    | 'patient'
    | 'prescription'
    | 'dosage'
    | 'course'
    | 'safety'
    | 'monitoring'
    | 'inventory'
    | 'billing'
    | 'reminders'
    | 'documents'
    | 'sharing';
  type:
    | 'text'
    | 'number'
    | 'select'
    | 'multiselect'
    | 'date'
    | 'time_array'
    | 'toggle'
    | 'textarea'
    | 'family_picker';
  requiredInModes?: string[]; // e.g. ['simple', 'expert']
  recommendedInPresets?: string[]; // e.g. ['doctor', 'pharmacist']
  options?: string[];
  placeholder?: string;
  defaultValue?: any;
}

export interface FormCategoryDef {
  id: string;
  label: string;
  icon: string;
  description: string;
  fields: FormFieldDef[];
}

export type MedicineMode = 'simple' | 'advanced' | 'expert' | 'custom';
export type PresetType = 'personal' | 'caregiver' | 'doctor' | 'pharmacist' | 'clinic' | 'custom';

export type DoseStatusType =
  | 'SCHEDULED'
  | 'UPCOMING'
  | 'DUE'
  | 'TAKEN'
  | 'LATE'
  | 'MISSED'
  | 'SKIPPED'
  | 'SNOOZED'
  | 'CANCELLED'
  | 'HELD';

export interface ConditionalRule {
  id: string;
  name: string;
  conditionField: string;
  operator: 'equals' | 'contains' | 'in' | 'is_truthy';
  conditionValue: any;
  action: 'show' | 'hide' | 'require';
  targetFields: string[];
  description: string;
  enabled: boolean;
}

